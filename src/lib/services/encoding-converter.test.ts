describe('detectEncoding', () => {
	it('detects UTF-8 without consulting jschardet', () => {
		expect(detectEncoding(SAMPLE_BYTES_UTF8)).toMatchObject({ encoding: 'utf-8', confidence: 1 });
	});

	it('detects a UTF-8 BOM', () => {
		const withBom = new Uint8Array([0xef, 0xbb, 0xbf, ...SAMPLE_BYTES_UTF8]);
		expect(detectEncoding(withBom)).toMatchObject({ encoding: 'utf-8-bom', hasBom: true });
	});

	// jschardet 4 reports Shift_JIS text as "CP932" and simplified Chinese as
	// "GB18030"; both must map to the decoders the page offers.
	it.each([
		['Shift-JIS sample', SAMPLE_BYTES_SJIS, 'shift-jis'],
		['EUC-JP', EUC_JP_TEXT, 'euc-jp'],
		['GBK', GBK_TEXT, 'gbk'],
		['Big5', BIG5_TEXT, 'big5'],
	] as const)('detects %s text', (_label, bytes, expected) => {
		const detected = detectEncoding(bytes);
		expect(detected.encoding).toBe(expected);
		expect(detected.confidence).toBeGreaterThan(0);
		expect(detected.hasBom).toBe(false);
	});
});
